// Distinct layouts use the same world scale and movement rules.
export const COVER_KINDS = [
  "table",
  "crate",
  "log",
  "stone",
  "sofa",
  "bed",
  "cabinet",
  "barrel",
];
export const breakable = (p) =>
  p && (p.destructible === true || COVER_KINDS.includes(p.kind));
const slab = (x, y, w, material, h = 28, extra = {}) => ({
  x,
  y,
  w,
  h,
  material,
  ...extra,
});
const steps = (x, y, count, dx, dy, material) =>
  Array.from({ length: count }, (_, i) => i).filter(i => i % 2 === 0).map(i =>
    slab(
      x +
        i * dx +
        (!dx ? ((i / 2) % 2) * (x < 200 ? 150 : x > 2300 ? -150 : x < 1280 ? 160 : -160) : 0),
      y + i * dy,
      150,
      material,
      20,
    ),
  );
const lift = (x, y, w, travel) =>
  slab(x, y, w, "metal", 18, { elevator: true, travel, speed: 0.3 });
function map(
  name,
  theme,
  color,
  material,
  rows,
  spawnRows,
  hazards,
  options = {},
) {
  const platforms = rows.map((r) =>
    Array.isArray(r) ? slab(...r, material) : r,
  );
  const kinds = options.props || ["crate"];
  const sizes = {
    crate: [72, 64],
    log: [110, 42],
    stone: [92, 64],
    sofa: [124, 54],
    bed: [138, 42],
    cabinet: [62, 78],
    barrel: [54, 68],
    table: [90, 50],
  };
  const cover = platforms
    .filter((p) => p.w >= 300 && !p.move && !p.elevator)
    .flatMap((p, i) => {
      const kind = kinds[i % kinds.length],
        [w, h] = sizes[kind];
      return [
        {
          x: p.x + p.w * 0.5 - w / 2,
          y: p.y - h,
          w,
          h,
          hp: kind === "stone" ? 110 : 75,
          maxHp: kind === "stone" ? 110 : 75,
          kind,
        },
      ];
    });
  const spawns = spawnRows.map(([i, f = 0.2]) => [
    platforms[i].x + platforms[i].w * f,
    platforms[i].y - 42,
  ]);
  const guns = ["railgun", "barrage", "plasma", "shotgun", "minigun", "rocket"];
  const weapons = platforms
    .filter((p) => p.w >= 300 && !p.elevator && !p.move)
    .slice(0, 8)
    .map((p, i) => [p.x + p.w * 0.7, p.y - 90, guns[i % guns.length]]);
  return {
    name,
    theme,
    color,
    platforms,
    cover,
    spawns,
    weapons,
    hazards,
    spikes: [],
    ...options,
  };
}
